// Runs the labeled set through the real engine (classifier → rules → labels) and reports
// precision / recall per rule. `npm run eval` prints the table and writes tests/eval/REPORT.md.
import { writeFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { classify } from '../../src/background/classifier';
import { templateLabel } from '../../src/background/labels';
import { evaluate } from '../../src/background/rules';
import { syncInbox } from '../../src/background/tracker';
import { CONFIG } from '../../src/shared/config';
import type { PageFeatures, RuleId } from '../../src/shared/types';
import { MIN, NOW, stateWith, visit } from '../helpers';
import { CASES, type EvalCase } from './cases';

/** Precision/recall below these fail the run, so a rule change that makes detection worse is caught. */
const FLOOR = { precision: 0.85, recall: 0.85 };

const fullFeatures = (f: Partial<PageFeatures>): PageFeatures => ({
  formCount: 0, inputCount: 0, wordCount: 0, hasArticle: false, codeBlocks: 0, hasNav: false,
  videoDuration: 0, hasPassword: false, cartWords: false, cartEmpty: false, completionText: false, headings: [], ...f,
});

interface Shown { rule: RuleId; note: string; score: number }

/** What the panel would show for this case. */
function run(c: EvalCase): Shown[] {
  let s;
  if (c.unread) {
    s = stateWith([], { focusedTabId: null, windowFocused: true });
    const tab = (title: string) => [{ id: 1, url: c.url, title } as chrome.tabs.Tab];
    syncInbox(s, tab(c.unread.before), true, NOW - c.awayMin * MIN);
    syncInbox(s, tab(c.unread.now), true, NOW);
  } else {
    const features = c.features ? fullFeatures(c.features) : undefined;
    const v = visit({
      url: c.url,
      title: c.title,
      pageType: classify(c.url, features),
      cartEmpty: features?.cartEmpty,
      activeSec: c.activeSec,
      closed: !!c.closed,
      startedAt: NOW - c.awayMin * MIN - c.activeSec * 1000,
      lastActiveAt: NOW - c.awayMin * MIN,
      leftAt: NOW - c.awayMin * MIN,
      signals: c.signals,
    });
    s = stateWith([v], { focusedTabId: null, windowFocused: true });
  }
  return evaluate(s, NOW)
    .filter((x) => x.score >= CONFIG.showThreshold)
    .map((x) => ({ rule: x.rule, note: templateLabel(x).note, score: x.score }));
}

const pct = (n: number) => (Number.isFinite(n) ? `${Math.round(n * 100)}%` : '–');

describe('labeled evaluation set', () => {
  const rows = CASES.map((c) => ({ c, shown: run(c) }));
  const rules = [...new Set(CASES.map((c) => c.expect).filter((r): r is RuleId => !!r))];
  const stats = Object.fromEntries(rules.map((r) => [r, { tp: 0, fp: 0, fn: 0 }]));
  const misses: string[] = [];
  let noteRight = 0;
  let noteTotal = 0;

  for (const { c, shown } of rows) {
    const hit = shown.find((x) => x.rule === c.expect);
    if (c.expect) {
      stats[c.expect] ??= { tp: 0, fp: 0, fn: 0 };
      if (hit) stats[c.expect].tp++;
      else {
        stats[c.expect].fn++;
        misses.push(`MISSED  ${c.id}: expected ${c.expect}, got ${shown.map((x) => x.rule).join(', ') || 'nothing'} — ${c.story}`);
      }
      if (hit && c.note) {
        noteTotal++;
        if (hit.note === c.note) noteRight++;
        else misses.push(`LABEL   ${c.id}: expected "${c.note}", got "${hit.note}"`);
      }
    }
    for (const x of shown) {
      if (x.rule === c.expect) continue;
      (stats[x.rule] ??= { tp: 0, fp: 0, fn: 0 }).fp++;
      misses.push(`FALSE   ${c.id}: showed ${x.rule} (score ${x.score.toFixed(2)}), expected ${c.expect ?? 'nothing'} — ${c.story}`);
    }
  }

  const sum = Object.values(stats).reduce((a, b) => ({ tp: a.tp + b.tp, fp: a.fp + b.fp, fn: a.fn + b.fn }), { tp: 0, fp: 0, fn: 0 });
  const precision = sum.tp / (sum.tp + sum.fp);
  const recall = sum.tp / (sum.tp + sum.fn);
  const quiet = rows.filter((r) => !r.c.expect);
  const quietRight = quiet.filter((r) => r.shown.length === 0).length;

  const table = [
    '| Rule | Cases | Caught | False alarms | Missed | Precision | Recall |',
    '|---|---|---|---|---|---|---|',
    ...Object.entries(stats).map(([r, x]) => `| ${r} | ${CASES.filter((c) => c.expect === r).length} | ${x.tp} | ${x.fp} | ${x.fn} | ${pct(x.tp / (x.tp + x.fp))} | ${pct(x.tp / (x.tp + x.fn))} |`),
    `| **All** | ${CASES.length} | ${sum.tp} | ${sum.fp} | ${sum.fn} | **${pct(precision)}** | **${pct(recall)}** |`,
  ].join('\n');

  const report = [
    '# Detection evaluation',
    '',
    `Generated by \`npm run eval\` from ${CASES.length} labeled cases in \`tests/eval/cases.ts\`.`,
    'Precision = of the things shown, how many were really unfinished. Recall = of the unfinished things, how many were shown.',
    '',
    table,
    '',
    `- Should stay quiet: ${quietRight} of ${quiet.length} correct`,
    `- Status text correct: ${noteRight} of ${noteTotal}`,
    `- Pass floor: precision ≥ ${pct(FLOOR.precision)}, recall ≥ ${pct(FLOOR.recall)}`,
    '',
    '## Misses',
    '',
    misses.length ? misses.map((m) => `- ${m}`).join('\n') : 'None.',
    '',
  ].join('\n');

  writeFileSync(new URL('./REPORT.md', import.meta.url), report);
  console.log(`\n${table}\n\nQuiet cases correct: ${quietRight}/${quiet.length} · Status text correct: ${noteRight}/${noteTotal}\n${misses.join('\n')}\n`);

  it(`precision ≥ ${pct(FLOOR.precision)}`, () => expect(precision).toBeGreaterThanOrEqual(FLOOR.precision));
  it(`recall ≥ ${pct(FLOOR.recall)}`, () => expect(recall).toBeGreaterThanOrEqual(FLOOR.recall));
  it('status text matches for every caught case', () => expect(noteRight).toBe(noteTotal));
});
